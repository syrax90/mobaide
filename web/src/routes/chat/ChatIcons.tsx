/**
 * Glyphs on the chrome's 16-unit pixel grid, drawn from row maps (`#` = on)
 * and merged into horizontal runs once at load. Decorative: every control
 * that carries one has its own accessible name.
 */
type Run = readonly [x: number, y: number, width: number];

function runs(rows: readonly string[]): Run[] {
  const out: Run[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x += 1;
        continue;
      }
      const start = x;
      while (row[x] === '#') x += 1;
      out.push([start, y, x - start]);
    }
  });
  return out;
}

function glyph(rows: readonly string[]) {
  const shape = runs(rows);
  return function PixelGlyph({ className = 'chat-icon' }: { className?: string }) {
    return (
      <svg className={className} viewBox="0 0 16 16" aria-hidden="true" focusable="false">
        {shape.map(([x, y, width]) => (
          <rect key={`${String(x)}-${String(y)}`} x={x} y={y} width={width} height={1} />
        ))}
      </svg>
    );
  };
}

