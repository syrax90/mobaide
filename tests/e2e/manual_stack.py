def merge_external_install_state(state_dir: Path, state: dict) -> None:
    """Fold in install bookkeeping a concurrent client subcommand wrote.

    The READY banner tells the operator to run ``ios --install-app`` from
    another shell while ``up`` keeps streaming logs. That process records its
    install in state.json, but ``up`` still holds the pre-install dictionary and
    its shutdown save would put the old one back -- costing the next install a
    needless device-wide keychain reset. Disk wins for these keys: ``up`` only
    ever installs during startup, so anything on disk is at least as fresh.
    """
    try:
        on_disk = json.loads((state_dir / "state.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return
    for key in ("android", "ios"):
        external = (on_disk.get(key) or {}).get("installed_urls")
        if isinstance(external, dict) and external:
            client = state.setdefault(key, _default_client_state())
            client.setdefault("installed_urls", {}).update(external)


def cmd_up(args: argparse.Namespace) -> int:
    deps = load_deps(auto_install=True, reinstall=args.reinstall)
    report_checkout_code()

    state_dir = args.state_dir
    running = _read_state(state_dir)
    if running and recorded_live_process(
        running.get("runtime") or {}, "up", deps.psutil
    ) is not None:
        # One stack per state dir (and port). Taking over instead of failing on
        # "port busy" is what lets main and a worktree swap with a bare `up`.
        log("another stack is running with this state dir; stopping it first")
        stop_running_stack(state_dir, running, deps.psutil, DEFAULT_STOP_TIMEOUT)
        wait_for_port_release(args.host or running.get("server_host") or DEFAULT_HOST,
                              args.port or running.get("server_port") or DEFAULT_PORT)
    preserved_clients: dict[str, dict] = {}
    adopted_emulator: dict = {}
    if args.fresh and (state_dir / "state.json").exists():
        # Consume the old state BEFORE deleting it: reap any crashed run's
        # children (their pids live only here) and carry the per-client
        # ownership metadata over, or a later `--revert` would mistake our own
        # generated CENTRAL_SERVER_URL for the user's original value.
        try:
            old_state = json.loads((state_dir / "state.json").read_text(encoding="utf-8"))
        except (OSError, ValueError):
            old_state = None
        if old_state:
            adopted_emulator = carry_over_emulator(
                old_state.get("runtime") or {}, args, deps.psutil
            )
            kill_stale_processes(old_state, deps.psutil)
            preserved_clients = {
                key: old_state[key]
                for key in ("android", "ios")
                if old_state.get(key)
            }
    if args.fresh and state_dir.exists():
        log(f"--fresh: wiping state dir {state_dir}")
        shutil.rmtree(state_dir, ignore_errors=True)

    server_dir = state_dir / "server"
    agent_dir = state_dir / "agent"
    logs_dir = state_dir / "logs"
    for d in (server_dir, agent_dir, logs_dir):
        d.mkdir(parents=True, exist_ok=True)

    state = load_or_create_state(state_dir, args)
    state.update(preserved_clients)
    save = lambda: save_state(state_dir, state)  # noqa: E731
    save()

    adopted_emulator = adopted_emulator or carry_over_emulator(
        state.get("runtime") or {}, args, deps.psutil
    )
    kill_stale_processes(state, deps.psutil)
    stop_request = state_dir / STOP_REQUEST_NAME
    stop_request.unlink(missing_ok=True)  # a leftover must not stop this run
    # Recorded before anything is spawned so `stop` can find this run and,
    # after a hard kill, reap exactly what it left behind ("synced" and "keep"
    # carry what teardown would have restored and the opt-outs it honors).
    state["runtime"] = {
        "started_at": _utc_now(),
        "checkout": str(REPO_ROOT),
        "synced": [],
        "keep": [
            name for name, kept in (
                ("android", args.keep_android),
                ("ios", args.keep_ios),
                ("emulator", args.keep_emulator),
            ) if kept
        ],
        **adopted_emulator,
    }
    record_runtime_process(state, "up", os.getpid(), deps.psutil)
    save()
    check_port_free(args.host, args.port)
    probe_host = local_probe_host(args.host)

    npm = None
    if args.web:
        # Fail fast (npm missing, port busy, npm ci broken) before any child exists.
        npm = find_npm()
        check_port_free("127.0.0.1", args.web_port, flag="--web-port")
        ensure_web_install(npm)

    lan_ip, all_ips = detect_lan_ips(deps.psutil)
    if args.advertise_ip:
        lan_ip = args.advertise_ip
    elif args.host not in ("0.0.0.0", "::", "127.0.0.1", "localhost"):
        lan_ip = args.host  # bound to one interface: that IS the reachable IP

    android = client_sync_state()
    ios = client_sync_state()
    emulator = None
    android_installed = False
    simulator_udid = None
    ios_installed = False
    children: list[ChildProcess] = []
    client = None
    exit_code = 0
    # The client sync, emulator boot and app install run inside the guard too:
    # Ctrl+C or SIGTERM during a minutes-long Gradle build or emulator boot
    # must still stop an owned emulator and restore the client files.
    try:
        if not args.no_android:
            android.url = resolve_android_url(args, lan_ip)
            state["runtime"]["synced"].append("android")
            android.rebuild_needed = sync_android_files(state, android.url, save)
            android.synced = True
            default_emulator_when_no_device(args)
            if args.emulator:
                # Launched first so its boot overlaps the Gradle build and the
                # server/agent startup below.
                emulator = start_emulator(args.emulator, logs_dir / "emulator.log")
                if emulator is not None:
                    record_emulator(state, emulator, deps.psutil)
                    save()
            if args.install_app:
                android_installed = install_on_emulator_or_device(
                    emulator, logs_dir / "emulator.log",
                    emulator_requested=bool(args.emulator),
                )
        elif args.emulator:
            log("--emulator ignored: --no-android")

        if not args.no_ios:
            if sys.platform == "darwin" or args.ios:
                ios.url = resolve_ios_url(args, lan_ip)
                state["runtime"]["synced"].append("ios")
                ios.rebuild_needed = sync_ios_files(state, ios.url, save)
                ios.synced = True
                if args.install_app or args.simulator:
                    simulator_udid = prepare_simulator(args.simulator)
                    if simulator_udid is not None:
                        state["runtime"]["simulator_udid"] = simulator_udid
                        save()
                if args.install_app:
                    ios_installed = run_xcode_install(
                        state, state_dir, ios.url, save,
                        reset_keychain=not args.ios_keep_keychain,
                        udid=simulator_udid,
                    )
            else:
                log("iOS sync skipped: not macOS (pass --ios to write "
                    "ios/Config/Local.xcconfig anyway)")

        if os.name == "nt" and args.host not in ("127.0.0.1", "localhost"):
            log(
                f"binding {args.host}: watch for the Windows Defender Firewall prompt on "
                "first run and ALLOW Python on Private networks, or the phone cannot connect"
            )

        log(f"starting central_server on {args.host}:{args.port} (MOBAIDE_ENV=test)")
        server = ChildProcess(
            "server",
            [sys.executable, "-u", "-m", "central_server"],
            build_server_env(state, args, server_dir),
            server_dir,
            logs_dir / "server.log",
        )
        children.append(server)
        record_runtime_process(state, "server", server.proc.pid, deps.psutil)
        save()
        wait_for_http_ok(
            deps,
            f"http://{probe_host}:{args.port}/api/health",
            timeout=90,
            child=server,
        )

        client = deps.mmc.MockMobileClient(f"http://{probe_host}:{args.port}")
        provision(deps, client, state, save)

        agent_port = free_loopback_port()
        mode = "fake echo PTY (test mode)" if args.fake_pty else "real PTY (production mode)"
        log(f"starting mobaide agent with {mode}")
        agent = ChildProcess(
            "agent",
            [sys.executable, "-u", "-m", "mobaide"],
            build_agent_env(state, args, agent_dir, agent_port),
            agent_dir,
            logs_dir / "agent.log",
        )
        children.append(agent)
        record_runtime_process(state, "agent", agent.proc.pid, deps.psutil)
        save()
        wait_for_http_ok(
            deps,
            f"http://127.0.0.1:{agent_port}/api/health",
            timeout=60,
            child=agent,
            expect_status_ok=True,
        )
        # The 4012-safe gate: agent's relay tunnel is up, not just its HTTP port.
        # agents_online is admin-gated, so poll with the seeded admin's token, not
        # the app-owner's (which the agent-ownership endpoints reject as admin).
        admin_token = client.login(_HEALTH_ADMIN_EMAIL, _HEALTH_ADMIN_PASSWORD)
        client.wait_agents_online(1, timeout=45, token=admin_token)
        log("agent tunnel is online (agents_online >= 1)")

        if args.smoke:
            if args.fake_pty:
                run_smoke(deps, client, state)
            else:
                log("--smoke needs --fake-pty (deterministic echo backend); skipping")

        # Web boots last so a server/agent startup failure never has vite log
        # lines interleaved into its diagnostics; the Vite proxy connects per
        # request, so nothing here depends on boot order.
        if args.web:
            assert npm is not None  # resolved by the pre-boot --web block
            log(f"starting web client (vite dev) on http://localhost:{args.web_port}")
            web = ChildProcess(
                "web",
                [npm, "run", "dev", "--", "--port", str(args.web_port), "--strictPort"],
                build_web_env(args, state),
                WEB_DIR,
                logs_dir / "web.log",
                ignore_console_ctrl_c=True,
            )
            children.append(web)
            record_runtime_process(state, "web", web.proc.pid, deps.psutil)
            state["runtime"]["web_port"] = args.web_port
            save()
            wait_for_http_ok(
                deps, f"http://localhost:{args.web_port}/", timeout=90, child=web
            )

        print_ready_banner(args, state, lan_ip, all_ips, android, ios, emulator,
                           simulator_udid)

        if args.web and not args.no_browser:
            open_web_client(args.web_port)
        # Only now: launched earlier, the apps would try to sign in to a server
        # that is not listening yet.
        if android_installed and emulator is not None:
            launch_android_app(emulator, state)
        if ios_installed and simulator_udid is not None:
            launch_ios_app(simulator_udid, state)

        while True:
            time.sleep(1)
            if stop_request.exists():
                log("stop requested (`manual_stack.py stop`): shutting down")
                return exit_code
            for child in children:
                if not child.alive():
                    child.dump_tail()
                    log(f"{child.name} exited unexpectedly "
                        f"(code {child.proc.returncode}); shutting down")
                    exit_code = 1
                    return exit_code
    except KeyboardInterrupt:
        log("Ctrl+C: shutting down")
        return exit_code
    finally:
        for child in reversed(children):  # reverse boot order
            child.stop(deps.psutil)
        if client is not None:
            client.close()
        if not args.keep_emulator:
            stop_recorded_emulator(state["runtime"], deps.psutil)
        stop_request.unlink(missing_ok=True)
        state["runtime"] = {}
        state_exists = (state_dir / "state.json").exists()
        if state_exists:
            merge_external_install_state(state_dir, state)
        # Restore the checkout to its pre-test state so a normal or release
        # build is not left pointing at the throwaway stack. The installed debug
        # app keeps its baked-in URL, so this neither disconnects the phone nor
        # triggers a spurious rebuild prompt on the next `up` (see baked_url).
        # Skipped when state.json is gone (a concurrent `clean` already reverted,
        # and revert_android_files would re-create the deleted state dir).
        restored = []
        if android.synced and not args.keep_android and state_exists:
            try:
                revert_android_files(state, save)
                restored.append("android/local.properties")
            except OSError as exc:
                log(f"could not restore android/local.properties on stop ({exc}); "
                    "run `python tests/e2e/manual_stack.py android --revert` manually")
        if ios.synced and not args.keep_ios and state_exists:
            try:
                revert_ios_files(state, save)
                restored.append("ios/Config/Local.xcconfig")
            except OSError as exc:
                log(f"could not restore ios/Config/Local.xcconfig on stop ({exc}); "
                    "run `python tests/e2e/manual_stack.py ios --revert` manually")
        if state_exists:
            # Skip the save when `clean` removed the state dir mid-run --
            # rewriting it here would resurrect a directory the user deleted.
            save()
        stop_msg = f"stack stopped; state kept in {state_dir} (next `up` reuses it)"
        if restored:
            stop_msg += f"; {' + '.join(restored)} restored"
        log(stop_msg)


def advertised_lan_ip(args: argparse.Namespace) -> str:
    """LAN IP for a client subcommand run outside `up` (psutil optional)."""
    if args.advertise_ip:
        return args.advertise_ip
    psutil_mod = None
    try:
        import psutil as psutil_mod  # type: ignore[no-redef]
    except ImportError:
        pass  # candidates list degrades gracefully; primary detection is stdlib
    lan_ip, _ = detect_lan_ips(psutil_mod)
    return lan_ip


def cmd_android(args: argparse.Namespace) -> int:
    state_dir = args.state_dir
    state = load_or_create_state(state_dir, args)
    save = lambda: save_state(state_dir, state)  # noqa: E731

    if args.revert:
        revert_android_files(state, save)
        return 0

    url = resolve_android_url(args, advertised_lan_ip(args))
    changed = sync_android_files(state, url, save)
    if changed:
        log("URL changed: rebuild + reinstall the debug app so it bakes the new value")
    emulator = None
    log_path = args.state_dir / "logs" / "emulator.log"
    default_emulator_when_no_device(args)
    if args.emulator:
        # Not recorded as owned: a one-shot command has no teardown, so an
        # emulator it boots simply stays up for the testing that follows.
        log_path.parent.mkdir(parents=True, exist_ok=True)
        emulator = start_emulator(args.emulator, log_path)
        if emulator is not None and not args.install_app:
            wait_for_emulator(emulator, log_path)
    if args.install_app and install_on_emulator_or_device(
        emulator, log_path, emulator_requested=bool(args.emulator)
    ) and emulator is not None:
        launch_android_app(emulator, state)
    return 0


def cmd_ios(args: argparse.Namespace) -> int:
    state_dir = args.state_dir
    state = load_or_create_state(state_dir, args)
    save = lambda: save_state(state_dir, state)  # noqa: E731

    if args.revert:
        revert_ios_files(state, save)
        return 0

    url = resolve_ios_url(args, advertised_lan_ip(args))
