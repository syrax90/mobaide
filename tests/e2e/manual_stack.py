def cmd_up(args: argparse.Namespace) -> int:
    deps = load_deps(auto_install=True, reinstall=args.reinstall)

    state_dir = args.state_dir
    preserved_clients: dict[str, dict] = {}
    if args.fresh and (state_dir / "state.json").exists():
        # Consume the old state BEFORE deleting it: reap any crashed run's
        # children (their pids live only here) and carry the per-client
        # ownership metadata over, or a later `--revert` would mistake our own
        # generated CENTRAL_SERVER_URL for the user's original value.
        try:
            old_state = json.loads((state_dir / "state.json").read_text(encoding="utf-8"))
        except (OSError, ValueError):
            old_state = None
        if old_state:
            kill_stale_processes(old_state, deps.psutil)
            preserved_clients = {
                key: old_state[key]
                for key in ("android", "ios")
                if old_state.get(key)
            }
    if args.fresh and state_dir.exists():
        log(f"--fresh: wiping state dir {state_dir}")
        shutil.rmtree(state_dir, ignore_errors=True)

    server_dir = state_dir / "server"
    agent_dir = state_dir / "agent"
    logs_dir = state_dir / "logs"
    for d in (server_dir, agent_dir, logs_dir):
        d.mkdir(parents=True, exist_ok=True)

    state = load_or_create_state(state_dir, args)
    state.update(preserved_clients)
    save = lambda: save_state(state_dir, state)  # noqa: E731
    save()

    kill_stale_processes(state, deps.psutil)
    check_port_free(args.host, args.port)
    probe_host = local_probe_host(args.host)

    lan_ip, all_ips = detect_lan_ips(deps.psutil)
    if args.advertise_ip:
        lan_ip = args.advertise_ip
    elif args.host not in ("0.0.0.0", "::", "127.0.0.1", "localhost"):
        lan_ip = args.host  # bound to one interface: that IS the reachable IP

    android = client_sync_state()
    if not args.no_android:
        android.url = resolve_android_url(args, lan_ip)
        android.rebuild_needed = sync_android_files(state, android.url, save)
        android.synced = True
        if args.install_app:
            run_gradle_install()

    ios = client_sync_state()
    if not args.no_ios:
        if sys.platform == "darwin" or args.ios:
            ios.url = resolve_ios_url(args, lan_ip)
            ios.rebuild_needed = sync_ios_files(state, ios.url, save)
            ios.synced = True
            if args.install_app:
                run_xcode_install(
                    state, state_dir, ios.url, save,
                    reset_keychain=not args.ios_keep_keychain,
                )
        else:
            log("iOS sync skipped: not macOS (pass --ios to write "
                "ios/Config/Local.xcconfig anyway)")

    if os.name == "nt" and args.host not in ("127.0.0.1", "localhost"):
        log(
            f"binding {args.host}: watch for the Windows Defender Firewall prompt on "
            "first run and ALLOW Python on Private networks, or the phone cannot connect"
        )

    server = None
    agent = None
    client = None
    exit_code = 0
    try:
        log(f"starting central_server on {args.host}:{args.port} (MOBAIDE_ENV=test)")
        server = ChildProcess(
            "server",
            [sys.executable, "-u", "-m", "central_server"],
            build_server_env(state, args, server_dir),
            server_dir,
            logs_dir / "server.log",
        )
        state["runtime"] = {"started_at": _utc_now()}
        record_runtime_process(state, "server", server.proc.pid, deps.psutil)
        save()
        wait_for_http_ok(
            deps,
            f"http://{probe_host}:{args.port}/api/health",
            timeout=90,
            child=server,
        )

        client = deps.mmc.MockMobileClient(f"http://{probe_host}:{args.port}")
        provision(deps, client, state, save)

        agent_port = free_loopback_port()
        mode = "fake echo PTY (test mode)" if args.fake_pty else "real PTY (production mode)"
        log(f"starting mobaide agent with {mode}")
        agent = ChildProcess(
            "agent",
            [sys.executable, "-u", "-m", "mobaide"],
            build_agent_env(state, args, agent_dir, agent_port),
            agent_dir,
            logs_dir / "agent.log",
        )
        record_runtime_process(state, "agent", agent.proc.pid, deps.psutil)
        save()
        wait_for_http_ok(
            deps,
            f"http://127.0.0.1:{agent_port}/api/health",
            timeout=60,
            child=agent,
            expect_status_ok=True,
        )
        # The 4012-safe gate: agent's relay tunnel is up, not just its HTTP port.
        # agents_online is admin-gated, so poll with the seeded admin's token, not
        # the app-owner's (which the agent-ownership endpoints reject as admin).
        admin_token = client.login(_HEALTH_ADMIN_EMAIL, _HEALTH_ADMIN_PASSWORD)
        client.wait_agents_online(1, timeout=45, token=admin_token)
        log("agent tunnel is online (agents_online >= 1)")

        if args.smoke:
            if args.fake_pty:
                run_smoke(deps, client, state)
            else:
                log("--smoke needs --fake-pty (deterministic echo backend); skipping")

        print_ready_banner(args, state, lan_ip, all_ips, android, ios)

        while True:
            time.sleep(1)
            for child in (server, agent):
                if not child.alive():
                    child.dump_tail()
                    log(f"{child.name} exited unexpectedly "
                        f"(code {child.proc.returncode}); shutting down")
                    exit_code = 1
                    return exit_code
    except KeyboardInterrupt:
        log("Ctrl+C: shutting down")
        return exit_code
    finally:
        for child in (agent, server):  # reverse boot order
            if child is not None:
                child.stop(deps.psutil)
        if client is not None:
            client.close()
        state["runtime"] = {}
        state_exists = (state_dir / "state.json").exists()
        # Restore the checkout to its pre-test state so a normal or release
        # build is not left pointing at the throwaway stack. The installed debug
        # app keeps its baked-in URL, so this neither disconnects the phone nor
        # triggers a spurious rebuild prompt on the next `up` (see baked_url).
        # Skipped when state.json is gone (a concurrent `clean` already reverted,
        # and revert_android_files would re-create the deleted state dir).
        restored = []
        if android.synced and not args.keep_android and state_exists:
            try:
                revert_android_files(state, save)
                restored.append("android/local.properties")
            except OSError as exc:
                log(f"could not restore android/local.properties on stop ({exc}); "
                    "run `python tests/e2e/manual_stack.py android --revert` manually")
        if ios.synced and not args.keep_ios and state_exists:
            try:
                revert_ios_files(state, save)
                restored.append("ios/Config/Local.xcconfig")
            except OSError as exc:
                log(f"could not restore ios/Config/Local.xcconfig on stop ({exc}); "
                    "run `python tests/e2e/manual_stack.py ios --revert` manually")
        if state_exists:
            # Skip the save when `clean` removed the state dir mid-run --
            # rewriting it here would resurrect a directory the user deleted.
            save()
        stop_msg = f"stack stopped; state kept in {state_dir} (next `up` reuses it)"
        if restored:
            stop_msg += f"; {' + '.join(restored)} restored"
        log(stop_msg)


def advertised_lan_ip(args: argparse.Namespace) -> str:
    """LAN IP for a client subcommand run outside `up` (psutil optional)."""
    if args.advertise_ip:
        return args.advertise_ip
    psutil_mod = None
    try:
        import psutil as psutil_mod  # type: ignore[no-redef]
    except ImportError:
        pass  # candidates list degrades gracefully; primary detection is stdlib
    lan_ip, _ = detect_lan_ips(psutil_mod)
    return lan_ip


def cmd_android(args: argparse.Namespace) -> int:
    state_dir = args.state_dir
    state = load_or_create_state(state_dir, args)
    save = lambda: save_state(state_dir, state)  # noqa: E731

    if args.revert:
        revert_android_files(state, save)
        return 0

    url = resolve_android_url(args, advertised_lan_ip(args))
    changed = sync_android_files(state, url, save)
    if changed:
        log("URL changed: rebuild + reinstall the debug app so it bakes the new value")
    if args.install_app:
        run_gradle_install()
    return 0


def cmd_ios(args: argparse.Namespace) -> int:
    state_dir = args.state_dir
    state = load_or_create_state(state_dir, args)
    save = lambda: save_state(state_dir, state)  # noqa: E731

    if args.revert:
        revert_ios_files(state, save)
        return 0

    url = resolve_ios_url(args, advertised_lan_ip(args))
    changed = sync_ios_files(state, url, save)
    if changed:
        log("URL changed: rebuild + reinstall the app so it bakes the new value")
    if args.install_app:
        run_xcode_install(
            state, state_dir, url, save,
            reset_keychain=not args.ios_keep_keychain,
        )
    return 0


def cmd_status(args: argparse.Namespace) -> int:
    state_path = args.state_dir / "state.json"
    state = None
    if state_path.exists():
        try:
            state = json.loads(state_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            pass
    port = args.port or (state or {}).get("server_port") or DEFAULT_PORT

    if state:
        log(f"state dir: {args.state_dir}")
        log(f"account:   {state.get('email')}")
        log(f"agent:     {state.get('agent_name')} ({(state.get('agent_id') or '-')[:8]}...)")
        android = state.get("android") or {}
        if android.get("managed_url"):
            log(f"android:   CENTRAL_SERVER_URL={android['managed_url']}")
    else:
        log(f"no state at {state_path} (stack never ran with this --state-dir)")

    deps = load_deps(auto_install=False)
    probe = local_probe_host((state or {}).get("server_host") or DEFAULT_HOST)
    client = deps.mmc.MockMobileClient(f"http://{probe}:{port}", http_timeout=3.0)
    try:
        # agents_online/agents_registered are admin-gated. A server not booted
        # by this script's `up` (no admin seeded) just falls back to bare status.
        try:
            admin_token = client.login(_HEALTH_ADMIN_EMAIL, _HEALTH_ADMIN_PASSWORD)
        except (deps.httpx.HTTPError, RuntimeError):
            admin_token = None
        health = client.health(token=admin_token)
        log(
            f"server:    UP on port {port} -- status={health.get('status')} "
            f"agents_online={health.get('agents_online')} "
            f"agents_registered={health.get('agents_registered')}"
        )
        return 0
    except Exception as exc:  # noqa: BLE001
        log(f"server:    DOWN on port {port} ({type(exc).__name__})")
        return 1
    finally:
        client.close()


def cmd_clean(args: argparse.Namespace) -> int:
    state_dir = args.state_dir
    state_path = state_dir / "state.json"
    state = None
    if state_path.exists():
        try:
            state = json.loads(state_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            state = None

    if state:
        try:
            import psutil as psutil_mod

            kill_stale_processes(state, psutil_mod)
        except ImportError:
            log("psutil not installed; skipping stale-process reaping")
        revert_android_files(state, lambda: None)
        revert_ios_files(state, lambda: None)

    if state_dir.exists():
        if state_path.exists() or not any(state_dir.iterdir()):
            shutil.rmtree(state_dir, ignore_errors=True)
            log(f"removed state dir {state_dir}")
        else:
            die(
                f"{state_dir} does not look like a manual-stack state dir "
                "(no state.json); refusing to delete it"
            )
    else:
        log(f"state dir {state_dir} already absent")
    return 0


