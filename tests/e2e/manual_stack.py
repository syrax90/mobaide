def _import_deps() -> SimpleNamespace:
    import importlib.util

    import httpx
    import psutil

    import mock_mobile_client as mmc

    # mock_mobile_client only pulls in the agent package; probe central_server
    # too (without executing it) so a half-installed env still triggers the
    # first-run installer instead of dying later inside the server child.
    if importlib.util.find_spec("central_server") is None:
        raise ImportError("No module named 'central_server' (editable install missing)")
    return SimpleNamespace(httpx=httpx, psutil=psutil, mmc=mmc)


def _pip_install_editable() -> None:
    for package_dir in ("mobaide_agent", "central_server"):
        spec = f"{REPO_ROOT / package_dir}[dev]"
        cmd = [sys.executable, "-m", "pip", "install", "-e", spec]
        log(f"running: {' '.join(cmd)}")
        try:
            subprocess.run(cmd, check=True)
        except (subprocess.CalledProcessError, OSError) as exc:
            die(f"pip install failed for {spec}: {exc}\nManually {PIP_HINT}")


def load_deps(*, auto_install: bool = False, reinstall: bool = False) -> SimpleNamespace:
    """Import httpx/psutil/mock_mobile_client, optionally pip-installing first.

    Auto-install targets the interpreter running this script (sys.executable),
    which is printed so an accidental base-env run is at least visible.
    """
    global _DEPS
    if _DEPS is not None and not reinstall:
        return _DEPS
    if reinstall:
        log(f"--reinstall: refreshing editable installs into {sys.executable}")
        _pip_install_editable()
    try:
        deps = _import_deps()
    except ImportError as exc:
        if not auto_install:
            die(f"missing dependency ({exc}).\nTo fix, {PIP_HINT}")
        log(f"missing dependency ({exc}); installing into {sys.executable} ...")
        _pip_install_editable()
        try:
            deps = _import_deps()
        except ImportError as exc2:
            die(f"still missing after install ({exc2}).\nManually {PIP_HINT}")
    _DEPS = deps
    return deps


def ensure_no_proxy_env() -> None:
    """Keep loopback REST/WS traffic out of any corporate proxy (parent + children)."""
    for key in ("NO_PROXY", "no_proxy"):
        parts = [p.strip() for p in os.environ.get(key, "").split(",") if p.strip()]
        for host in ("127.0.0.1", "localhost"):
            if host not in parts:
                parts.append(host)
        os.environ[key] = ",".join(parts)


