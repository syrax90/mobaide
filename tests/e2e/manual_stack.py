def _add_common_args(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--state-dir",
        type=Path,
        default=DEFAULT_STATE_DIR,
        help=f"stack state location (default: {DEFAULT_STATE_DIR})",
    )


def _add_android_args(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--port", type=int, default=None,
                        help=f"central_server port (default: last used, then {DEFAULT_PORT})")
    parser.add_argument("--advertise-ip", default=None,
                        help="LAN IP to advertise instead of auto-detection")
    parser.add_argument(
        "--android-url",
        default="auto",
        metavar="MODE",
        help="URL baked into the app: auto | emulator (10.0.2.2) | reverse "
             "(127.0.0.1 via adb reverse) | an explicit http(s) URL",
    )
    parser.add_argument("--install-app", action="store_true",
                        help="run `gradlew :app:installDebug` after the file sync")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="manual_stack.py",
        description="Boot the Mobaide E2E stack for manual testing "
                    "(see docs/manual-e2e-testing.md)",
    )
    sub = parser.add_subparsers(dest="cmd", required=True)

    up = sub.add_parser("up", help="boot server + agent, sync android files, "
                                   "stream logs until Ctrl+C (default command)")
    _add_common_args(up)
    _add_android_args(up)
    up.add_argument("--host", default=DEFAULT_HOST,
                    help=f"server bind address (default {DEFAULT_HOST}; use "
                         "127.0.0.1 for an emulator-only, no-firewall-prompt run)")
    up.add_argument("--no-android", action="store_true",
                    help="do not touch android/local.properties or the debug "
                         "network-security override")
    up.add_argument("--fake-pty", action="store_true",
                    help="run the agent in MOBAIDE_ENV=test: fake echo PTY, no "
                         "real shells/CLIs (infra check mode)")
    up.add_argument("--smoke", action="store_true",
                    help="after boot, drive one echo session end-to-end "
                         "(requires --fake-pty)")
    up.add_argument("--fresh", action="store_true",
                    help="wipe the state dir first: new secret, account, agent, DB")
    up.add_argument("--email", default=None, help=f"account email (default {DEFAULT_EMAIL})")
    up.add_argument("--password", default=None, help="account password")
    up.add_argument("--agent-name", default=None,
                    help=f"agent display name (default {DEFAULT_AGENT_NAME})")
    up.add_argument("--projects", default=None,
                    help="optional PROJECTS seed for the agent (real project dirs)")
    up.add_argument("--reinstall", action="store_true",
                    help="re-run the editable pip installs before booting")
    up.set_defaults(func=cmd_up)

    android = sub.add_parser("android", help="sync (or revert) the two gitignored "
                                             "Android files without booting the stack")
    _add_common_args(android)
    _add_android_args(android)
    android.add_argument("--host", default=DEFAULT_HOST, help=argparse.SUPPRESS)
    android.add_argument("--revert", action="store_true",
                         help="remove the generated debug override and restore/"
                              "remove the CENTRAL_SERVER_URL line")
    android.set_defaults(func=cmd_android)

    status = sub.add_parser("status", help="probe /api/health and show the "
                                           "persisted stack identity")
    _add_common_args(status)
    status.add_argument("--port", type=int, default=None,
                        help="server port (default: last used, then 9000)")
    status.set_defaults(func=cmd_status)

    clean = sub.add_parser("clean", help="kill stale processes, revert android "
                                         "files, delete the state dir")
    _add_common_args(clean)
    clean.set_defaults(func=cmd_clean)

    return parser


def main(argv: list[str] | None = None) -> int:
    if sys.version_info < MIN_PYTHON:
        die(f"Python {MIN_PYTHON[0]}.{MIN_PYTHON[1]}+ required "
            f"(running {sys.version.split()[0]}); activate the right env")
    ensure_no_proxy_env()
    if os.name != "nt":
        # Make `kill <pid>` run the same finally-based teardown as Ctrl+C.
        signal.signal(signal.SIGTERM, lambda *_: sys.exit(143))

    argv = list(sys.argv[1:] if argv is None else argv)
    known = {"up", "android", "status", "clean"}
    if not argv:
        argv = ["up"]
    elif argv[0] not in known and argv[0] not in ("-h", "--help"):
        argv.insert(0, "up")

    args = build_parser().parse_args(argv)
    args.state_dir = Path(args.state_dir).expanduser().resolve()
    return args.func(args) or 0


if __name__ == "__main__":
    sys.exit(main())
