def free_loopback_port() -> int:
    """Reserve an ephemeral loopback port (no SO_REUSEADDR; mirrors conftest)."""
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]
    finally:
        s.close()


def check_port_free(host: str, port: int) -> None:
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        s.bind((host, port))
    except OSError as exc:
        die(
            f"port {port} on {host} is busy ({exc}).\n"
            "Another manual stack, the docker-compose dev server, or a crashed "
            "previous run may hold it.\n"
            "Try: python tests/e2e/manual_stack.py clean    (kills stale runs)\n"
            "or pick another port with --port."
        )
    finally:
        s.close()


def local_probe_host(bind_host: str) -> str:
    """Host the parent (and the co-located agent) should use to reach the server.

    A wildcard bind is reachable on loopback; a specific-interface bind is not,
    so probe/provision/relay traffic must target that interface instead.
    """
    return "127.0.0.1" if bind_host in ("0.0.0.0", "::", "") else bind_host


def detect_lan_ips(psutil_mod=None) -> tuple[str, list[str]]:
    """Best-guess LAN IPv4 (default-route trick; no packet is sent) + candidates."""
    primary = None
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        try:
            s.connect(("8.8.8.8", 80))
            primary = s.getsockname()[0]
        finally:
            s.close()
    except OSError:
        pass
    candidates: list[str] = []
    if psutil_mod is not None:
        try:
            for addrs in psutil_mod.net_if_addrs().values():
                for addr in addrs:
                    if addr.family == socket.AF_INET and not addr.address.startswith(
                        ("127.", "169.254.")
                    ):
                        candidates.append(addr.address)
        except Exception:  # noqa: BLE001 - candidates are best-effort only
            pass
    ordered: list[str] = []
    for ip in ([primary] if primary else []) + candidates:
        if ip and ip not in ordered:
            ordered.append(ip)
    if not ordered:
        ordered.append("127.0.0.1")
    return ordered[0], ordered


