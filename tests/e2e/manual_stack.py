def wait_for_http_ok(
    deps, url: str, *, timeout: float, child: ChildProcess, expect_status_ok: bool = False
) -> None:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if not child.alive():
            child.dump_tail()
            die(f"{child.name} exited with code {child.proc.returncode} during startup "
                f"(last log lines above; full log in the state dir)")
        try:
            resp = deps.httpx.get(url, timeout=1.5)
            if resp.status_code == 200 and (
                not expect_status_ok or resp.json().get("status") == "ok"
            ):
                return
        except Exception:  # noqa: BLE001 - not up yet
            pass
        time.sleep(0.5)
    child.dump_tail()
    die(f"{child.name} did not become ready within {timeout:.0f}s ({url})")


def provision(deps, client, state: dict, save) -> None:
    """Login (register on first run) and ensure the persisted agent exists."""
    try:
        client.register_and_login(state["email"], state["password"])
    except (deps.httpx.HTTPError, RuntimeError) as exc:
        die(
            f"could not log in as {state['email']} ({exc}).\n"
            "The credentials in state.json no longer match the server DB.\n"
            "Rerun with --fresh (new account) or pass matching --email/--password."
        )
    if state.get("agent_id") and state.get("agent_token"):
        known_ids = {a.get("agent_id") for a in client.list_agents()}
        if state["agent_id"] in known_ids:
            log(f"reusing agent '{state['agent_name']}' ({state['agent_id'][:8]}...)")
            return
        log("persisted agent no longer exists on the server; creating a new one")
    agent_id, agent_token = client.create_agent(state["agent_name"])
    state["agent_id"] = agent_id
    state["agent_token"] = agent_token
    save()  # persist BEFORE the agent boots: the raw token is shown only once
    log(f"created agent '{state['agent_name']}' ({agent_id[:8]}...)")


def run_smoke(deps, client, state: dict) -> None:
    """Deterministic echo round-trip through server + agent (fake PTY only)."""
    import asyncio

    if sys.platform == "win32":
        # websockets' asyncio client hangs under the Proactor loop (see conftest).
        asyncio.set_event_loop_policy(asyncio.WindowsSelectorEventLoopPolicy())
    marker = f"manual-stack-smoke-{secrets.token_hex(4)}".encode()
    mobile_token = client.mint_mobile_token(
        state["agent_id"], device_name="manual-stack-smoke"
    )
    session_id = client.create_shell_session(state["agent_id"], mobile_token)
    output = asyncio.run(
        client.drive_session(
            state["agent_id"],
            session_id,
            mobile_token,
            frame=deps.mmc.FRAME_INPUT + marker,
            expect=marker,
        )
    )
    log(f"smoke PASS: marker echoed through the relay ({len(output)} bytes)")


