def load_or_create_state(state_dir: Path, args: argparse.Namespace) -> dict:
    path = state_dir / "state.json"
    if path.exists():
        try:
            state = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            die(f"unreadable state file {path} ({exc}); rerun with --fresh")
        if state.get("version") != STATE_VERSION:
            die(f"state file {path} has version {state.get('version')} "
                f"(expected {STATE_VERSION}); rerun with --fresh")
    else:
        state = default_state()
    for attr in ("email", "password", "agent_name"):
        value = getattr(args, attr.replace("-", "_"), None)
        if value:
            state[attr] = value
    # Sticky port: an explicit --port wins and is remembered; otherwise reuse
    # the last-used port so bare re-runs (and `status`) stay consistent.
    if hasattr(args, "port"):
        if args.port:
            state["server_port"] = args.port
        else:
            args.port = state.get("server_port") or DEFAULT_PORT
    return state


def save_state(state_dir: Path, state: dict) -> None:
    state["updated_at"] = _utc_now()
    state_dir.mkdir(parents=True, exist_ok=True)
    path = state_dir / "state.json"
    path.write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8")
    if os.name != "nt":
        try:
            os.chmod(path, 0o600)  # state.json holds the JWT secret + agent token
        except OSError:
            pass


