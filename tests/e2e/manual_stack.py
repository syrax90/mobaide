def android_sdk_dir() -> Path | None:
    """ANDROID_HOME / ANDROID_SDK_ROOT, else Android Studio's per-OS default."""
    candidates = [os.environ.get("ANDROID_HOME"), os.environ.get("ANDROID_SDK_ROOT")]
    if os.name == "nt":
        local_app_data = os.environ.get("LOCALAPPDATA")
        if local_app_data:
            candidates.append(str(Path(local_app_data) / "Android" / "Sdk"))
    elif sys.platform == "darwin":
        candidates.append(str(Path.home() / "Library" / "Android" / "sdk"))
    else:
        candidates.append(str(Path.home() / "Android" / "Sdk"))
    for candidate in candidates:
        if candidate and Path(candidate).is_dir():
            return Path(candidate)
    return None


def sdk_tool(sdk: Path | None, *parts: str, windows_suffix: str = ".exe") -> str | None:
    """An SDK binary (adb, emulator, avdmanager) from the SDK, else from PATH."""
    name = parts[-1] + (windows_suffix if os.name == "nt" else "")
    if sdk is not None:
        path = sdk.joinpath(*parts[:-1], name)
        if path.exists():
            return str(path)
    return shutil.which(parts[-1])


def _run_tool(
    cmd: list[str], *, timeout: float = 30, stdin_text: str | None = None
) -> subprocess.CompletedProcess | None:
    try:
        return subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
            input=stdin_text,
            stdin=None if stdin_text is not None else subprocess.DEVNULL,
        )
    except (OSError, subprocess.SubprocessError):
        return None


def parse_adb_devices(output: str) -> dict[str, str]:
    """``adb devices`` -> {serial: state} (device / offline / unauthorized)."""
    devices: dict[str, str] = {}
    for line in output.splitlines():
        parts = line.split()
        if len(parts) >= 2 and not line.startswith(("*", "List of")):
            devices[parts[0]] = parts[1]
    return devices


def parse_avd_list(output: str) -> list[str]:
    """``emulator -list-avds`` names, minus any INFO/WARNING chatter."""
    return [
        line.strip() for line in output.splitlines()
        if re.fullmatch(r"[A-Za-z0-9._-]+", line.strip())
    ]


def pick_system_image(sdk: Path, machine: str | None = None) -> str | None:
    """sdkmanager id of the best installed phone image for this host's CPU.

    4 KB-page images beat the ``*_ps16k`` 16 KB-page ones (the app is not
    what is under test there), then the newest stable API level, then Play
    Store > Google APIs > AOSP. Previews (``android-CANARY``) and TV/Wear/
    Automotive images are never picked.
    """
    machine = (machine or platform.machine()).lower()
    abi = "arm64-v8a" if machine in ("arm64", "aarch64") else "x86_64"
    tag_rank = {"google_apis_playstore": 0, "google_apis": 1, "default": 2}
    best: tuple[tuple, str] | None = None
    for abi_dir in sdk.glob(f"system-images/android-*/*/{abi}"):
        api_dir, tag = abi_dir.parent.parent.name, abi_dir.parent.name
        match = re.fullmatch(r"android-(\d+)(?:\.(\d+))?", api_dir)
        base_tag = tag.removesuffix("_ps16k")
        if match is None or base_tag not in tag_rank:
            continue
        if not (abi_dir / "source.properties").exists():
            continue  # half-downloaded package
        key = (
            not tag.endswith("_ps16k"),
            int(match.group(1)),
            int(match.group(2) or 0),
            -tag_rank[base_tag],
        )
        if best is None or key > best[0]:
            best = (key, f"system-images;{api_dir};{tag};{abi}")
    return best[1] if best else None


def avd_config_path(name: str) -> Path:
    avd_home = os.environ.get("ANDROID_AVD_HOME")
    base = Path(avd_home) if avd_home else Path.home() / ".android" / "avd"
    return base / f"{name}.avd" / "config.ini"


def enable_hardware_keyboard(config_path: Path) -> None:
    """Let the host keyboard type into the emulator (avdmanager defaults to no).

    The app under test is a terminal; typing through the on-screen keyboard
    only is the main thing that makes manual testing on an emulator slow.
    """
    try:
        lines = config_path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return
    out = [line for line in lines if not line.startswith("hw.keyboard")]
    out.append("hw.keyboard=yes")
    config_path.write_text("\n".join(out) + "\n", encoding="utf-8")


def create_avd(sdk: Path | None, name: str) -> bool:
    """One-time AVD creation from the best installed system image."""
    avdmanager = sdk_tool(sdk, "cmdline-tools", "latest", "bin", "avdmanager",
                          windows_suffix=".bat")
    package = pick_system_image(sdk) if sdk is not None else None
    if avdmanager is None or package is None:
        missing = "avdmanager (SDK cmdline-tools)" if avdmanager is None else (
            "an installed phone system image")
        log(f"WARNING: AVD '{name}' does not exist and it cannot be created: "
            f"{missing} not found. Create it in Android Studio's Device Manager, "
            "or install an image with `sdkmanager \"system-images;android-36;"
            "google_apis;x86_64\"` and re-run")
        return False
    log(f"creating AVD '{name}' from {package} (one-time) ...")
    result = None
    # Hardware profile ids differ between cmdline-tools releases; fall back to
    # avdmanager's default profile when pixel_7 is unknown. "no" answers the
    # "custom hardware profile?" prompt.
    for device_args in (["--device", "pixel_7"], []):
        result = _run_tool(
            [avdmanager, "create", "avd", "--name", name, "--package", package,
             *device_args],
            timeout=180,
            stdin_text="no\n",
        )
        if result is not None and result.returncode == 0:
            enable_hardware_keyboard(avd_config_path(name))
            log(f"AVD '{name}' created")
            return True
    detail = (result.stderr or result.stdout).strip()[-400:] if result else "could not run"
    log(f"WARNING: avdmanager could not create AVD '{name}': {detail}")
    return False


def adb_devices(adb: str) -> dict[str, str]:
    result = _run_tool([adb, "devices"], timeout=30)
    return parse_adb_devices(result.stdout) if result and result.returncode == 0 else {}


def emulator_avd_name(adb: str, serial: str) -> str | None:
    result = _run_tool([adb, "-s", serial, "emu", "avd", "name"], timeout=10)
    if result is None or result.returncode != 0:
        return None
    first = result.stdout.strip().splitlines()
    return first[0].strip() if first else None


def _loopback_port_free(port: int) -> bool:
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        s.bind(("127.0.0.1", port))
        return True
    except OSError:
        return False
    finally:
        s.close()


def free_emulator_port(devices: dict[str, str]) -> int | None:
    """First even console port (and its odd adb port) nobody uses."""
    for port in range(5554, 5684, 2):
        if f"emulator-{port}" in devices:
            continue
        if _loopback_port_free(port) and _loopback_port_free(port + 1):
            return port
    return None


def start_emulator(avd: str, log_path: Path) -> SimpleNamespace | None:
    """Reuse the AVD if it already runs, else create (once) and launch it.

    Returns without waiting for the boot so callers can overlap it with other
    work; ``proc`` is None for a reused emulator (not ours to stop). Warn-only,
    like run_gradle_install: a missing SDK must never take the stack down.
    """
    sdk = android_sdk_dir()
    adb = sdk_tool(sdk, "platform-tools", "adb")
    emulator = sdk_tool(sdk, "emulator", "emulator")
    if adb is None or emulator is None:
        log("WARNING: Android SDK adb/emulator not found (set ANDROID_HOME); "
            "skipping the emulator")
        return None
    devices = adb_devices(adb)
    for serial, device_state in devices.items():
        if serial.startswith("emulator-") and device_state in ("device", "offline"):
            if emulator_avd_name(adb, serial) == avd:
                log(f"emulator '{avd}' is already running as {serial}; reusing it")
                return SimpleNamespace(avd=avd, serial=serial, adb=adb, proc=None)

    listed = _run_tool([emulator, "-list-avds"], timeout=60)
    if avd not in parse_avd_list(listed.stdout if listed else ""):
        if not create_avd(sdk, avd):
            return None
    port = free_emulator_port(devices)
    if port is None:
        log("WARNING: no free emulator console port in 5554-5682; "
            "skipping the emulator")
        return None

    # Detached from this console and process group: Ctrl+C here must not
    # hard-kill it (teardown asks it to shut down cleanly so its quick-boot
    # snapshot stays valid), and it is not a supervised child -- closing its
    # window must not take the stack down.
    detach: dict = (
        {"creationflags": subprocess.DETACHED_PROCESS | subprocess.CREATE_NEW_PROCESS_GROUP}
        if os.name == "nt" else {"start_new_session": True}
    )
    log(f"booting emulator '{avd}' as emulator-{port} (log: {log_path})")
    try:
        with open(log_path, "a", encoding="utf-8") as log_file:
            proc = subprocess.Popen(
                [emulator, "-avd", avd, "-port", str(port)],
                stdin=subprocess.DEVNULL,
                stdout=log_file,
                stderr=subprocess.STDOUT,
                **detach,
            )
    except OSError as exc:
        log(f"WARNING: could not launch the emulator ({exc})")
        return None
    return SimpleNamespace(avd=avd, serial=f"emulator-{port}", adb=adb, proc=proc)


def wait_for_emulator(emu: SimpleNamespace, log_path: Path,
                      timeout: float = EMULATOR_BOOT_TIMEOUT) -> bool:
    """Block until Android reports boot completed, then wake + unlock it."""
    deadline = time.monotonic() + timeout
    announced = False
    while time.monotonic() < deadline:
        if emu.proc is not None and emu.proc.poll() is not None:
            log(f"WARNING: the emulator exited during boot (code "
                f"{emu.proc.returncode}); see {log_path} -- usually missing "
                "hardware acceleration (enable the Windows Hypervisor Platform "
                "on Windows) or an AVD already open elsewhere")
            return False
        result = _run_tool(
            [emu.adb, "-s", emu.serial, "shell", "getprop", "sys.boot_completed"],
            timeout=15,
        )
        if result is not None and result.stdout.strip() == "1":
            # KEYCODE_WAKEUP + KEYCODE_MENU dismiss the swipe-only lock screen.
            _run_tool([emu.adb, "-s", emu.serial, "shell", "input", "keyevent", "224"])
            _run_tool([emu.adb, "-s", emu.serial, "shell", "input", "keyevent", "82"])
            log(f"emulator {emu.serial} is booted")
            return True
        if not announced:
            log(f"waiting for {emu.serial} to finish booting "
                f"(up to {timeout:.0f}s; a first cold boot takes minutes) ...")
            announced = True
        time.sleep(2)
    log(f"WARNING: {emu.serial} did not finish booting within {timeout:.0f}s")
    return False


def android_launch_command(state: dict) -> str:
    """The remote-shell ``am start`` line: one quoted string, because adb hands
    it to the device's sh, where the default password's ``>`` would redirect.

    ``-S --activity-clear-task`` always creates a fresh activity: without them
    a task left behind (e.g. under the notification-permission dialog) gets
    the intent "delivered to the top-most instance", and the extras are lost.
    """
    return shlex.join([
        "am", "start", "-S", "--activity-clear-task", "-n", ANDROID_MAIN_ACTIVITY,
        "-a", "android.intent.action.MAIN",
        "-c", "android.intent.category.LAUNCHER",
        "--es", ANDROID_DEV_LOGIN_EMAIL_EXTRA, state["email"],
        "--es", ANDROID_DEV_LOGIN_PASSWORD_EXTRA, state["password"],
    ])


def launch_android_app(emu: SimpleNamespace, state: dict) -> None:
    """Start the app with the stack's credentials, so a signed-out DEBUG build
    signs itself in (see DevLoginHandoff)."""
    result = _run_tool([
        emu.adb, "-s", emu.serial, "shell", android_launch_command(state),
    ])
    output = (result.stdout + result.stderr) if result is not None else ""
    if result is not None and result.returncode == 0 and "Error" not in output:
        log(f"launched {ANDROID_APP_ID} on {emu.serial} (signs in as "
            f"{state['email']} if signed out)")
    else:
        log(f"WARNING: could not launch {ANDROID_APP_ID} on {emu.serial} "
            f"({output.strip()[-200:] or 'adb failed'})")


def default_emulator_when_no_device(args: argparse.Namespace) -> None:
    """``--install-app`` with nothing attached boots the default AVD instead of
    letting Gradle fail on "no connected devices"."""
    if args.emulator or not args.install_app:
        return
    adb = sdk_tool(android_sdk_dir(), "platform-tools", "adb")
    if adb is None:
        return
    if any(state == "device" for state in adb_devices(adb).values()):
        return
    log(f"no Android device attached: using the emulator '{DEFAULT_AVD}'")
    args.emulator = DEFAULT_AVD


def record_emulator(state: dict, emu: SimpleNamespace, psutil_mod) -> None:
    """Mark an emulator this run booted as ours to shut down on stop."""
    if emu.proc is None:
        return
    record_runtime_process(state, "emulator", emu.proc.pid, psutil_mod)
    state["runtime"]["emulator_serial"] = emu.serial
    state["runtime"]["emulator_avd"] = emu.avd


def stop_recorded_emulator(runtime: dict, psutil_mod) -> None:
    """Shut down an emulator a run booted, cleanly first.

    ``adb emu kill`` lets it save its quick-boot snapshot (the next boot takes
    seconds instead of minutes); a hard kill is only the fallback.
    """
    proc = recorded_live_process(runtime, "emulator", psutil_mod)
    if proc is None:
        return
    serial = runtime.get("emulator_serial")
    log(f"shutting down the emulator this stack booted ({serial})")
    adb = sdk_tool(android_sdk_dir(), "platform-tools", "adb")
    if adb and serial:
        _run_tool([adb, "-s", serial, "emu", "kill"], timeout=15)
    try:
        proc.wait(timeout=30)
    except psutil_mod.TimeoutExpired:
        log("emulator did not shut down within 30s; killing it")
        kill_tree(psutil_mod, proc.pid)
    except psutil_mod.Error:
        pass


def install_on_emulator_or_device(
    emu: SimpleNamespace | None, log_path: Path, *, emulator_requested: bool
) -> bool:
    if emu is None:
        if emulator_requested:
            # An unpinned installDebug would replace the debug app on every
            # attached device, physical phones included.
            log("skipping the app install: the requested emulator is not available")
            return False
        return run_gradle_install()
    def ready_for_install() -> bool:
        if not wait_for_emulator(emu, log_path):
            return False
        # Updating a RUNNING app makes newer Androids (SystemUI's package-update
        # flow) relaunch it right after the install, racing the signed-in
        # launch below and dropping its extras. A stopped app is not relaunched.
        _run_tool([emu.adb, "-s", emu.serial, "shell", "am", "force-stop", ANDROID_APP_ID])
        return True

    return run_gradle_install(emu.serial, before_install=ready_for_install)


def carry_over_emulator(runtime: dict, args: argparse.Namespace, psutil_mod) -> dict:
    """Ownership of an emulator a hard-killed run booted.

    Adopted (so this run reuses it and stops it on exit) when this run asks
    for the same AVD, otherwise shut down -- the dead run would have.
    """
    if recorded_live_process(runtime, "emulator", psutil_mod) is None:
        return {}
    if args.emulator == runtime.get("emulator_avd") and not args.no_android:
        return {k: v for k, v in runtime.items() if k.startswith("emulator_")}
    stop_recorded_emulator(runtime, psutil_mod)
    return {}


def _runtime_version(runtime_id: str) -> tuple[int, ...]:
    """``com.apple.CoreSimulator.SimRuntime.iOS-26-0`` -> (26, 0)."""
    return tuple(int(n) for n in re.findall(r"\d+", runtime_id.rsplit(".", 1)[-1]))


def list_simulators() -> list[dict]:
    """Available iOS simulators, newest runtime first."""
    result = _run_tool(["xcrun", "simctl", "list", "devices", "available", "-j"], timeout=60)
    if result is None or result.returncode != 0:
        log("WARNING: could not list iOS simulators (`xcrun simctl` failed; "
            "is Xcode installed and selected with xcode-select?)")
        return []
    try:
        runtimes = json.loads(result.stdout).get("devices", {})
    except ValueError:
        return []
    sims = []
    for runtime in sorted(runtimes, key=_runtime_version, reverse=True):
        if ".iOS-" not in runtime:
            continue
        for device in runtimes[runtime]:
            if device.get("udid") and device.get("name"):
                sims.append({
                    "udid": device["udid"],
                    "name": device["name"],
                    "state": device.get("state", ""),
                    "runtime": runtime,
                })
    return sims


def pick_simulator(sims: list[dict], requested: str | None) -> dict | None:
    """The simulator to install on.

    An explicit name or UDID wins (a booted match first). Otherwise an already
    booted one -- ``iPhone 16`` among several -- so a tester's open simulator
    is reused; with none booted, ``iPhone 16``, then the newest iPhone.
    """
    if requested:
        matches = [s for s in sims if requested in (s["udid"], s["name"])]
        booted = [s for s in matches if s["state"] == "Booted"]
        return (booted or matches or [None])[0]
    booted = [s for s in sims if s["state"] == "Booted"]
    if booted:
        preferred = [s for s in booted if s["name"] == IOS_DEFAULT_SIM]
        return (preferred or booted)[0]
    preferred = [s for s in sims if s["name"] == IOS_DEFAULT_SIM]
    iphones = [s for s in sims if s["name"].startswith("iPhone")]
    return (preferred or iphones or sims or [None])[0]


def show_simulator(udid: str) -> None:
    """Bring Simulator.app to the front on this device.

    ``simctl boot`` alone boots a device headless: the app runs, but nobody
    can see it. The preference makes the window open on this device when
    Simulator.app starts; ``open`` then starts or activates it.
    """
    _run_tool(["defaults", "write", "com.apple.iphonesimulator",
               "CurrentDeviceUDID", udid], timeout=15)
    result = _run_tool(["open", "-a", "Simulator", "--args",
                        "-CurrentDeviceUDID", udid], timeout=30)
    if result is None or result.returncode != 0:
        log("WARNING: could not open Simulator.app; the simulator runs headless "
            "(open it from Xcode > Open Developer Tool > Simulator)")


def prepare_simulator(requested: str | None) -> str | None:
    """Boot (if needed) and show the simulator to use; its UDID, or None."""
    if sys.platform != "darwin":
        log("WARNING: the iOS simulator needs macOS; skipping it")
        return None
    sims = list_simulators()
    sim = pick_simulator(sims, requested)
    if sim is None:
        names = ", ".join(sorted({s["name"] for s in sims})) or "none"
        log(f"WARNING: no iOS simulator matches {requested or IOS_DEFAULT_SIM!r} "
            f"(available: {names}); pass --simulator NAME, or add an iOS "
            "runtime in Xcode > Settings > Components")
        return None
    udid = sim["udid"]
    if sim["state"] != "Booted":
        log(f"booting simulator '{sim['name']}' ({udid[:8]}...)")
        # Exit 149 = already booted (a race with another boot); bootstatus decides.
        _run_tool(["xcrun", "simctl", "boot", udid], timeout=120)
    status = _run_tool(["xcrun", "simctl", "bootstatus", udid, "-b"], timeout=300)
    if status is None or status.returncode != 0:
        log(f"WARNING: simulator '{sim['name']}' did not finish booting")
        return None
    show_simulator(udid)
    log(f"simulator '{sim['name']}' ({udid[:8]}...) is booted and shown")
    return udid


def launch_ios_app(udid: str, state: dict) -> bool:
    """Start the app with the stack's credentials, so a signed-out DEBUG build
    signs itself in (see LoginModel.signInWithDevLoginIfRequested)."""
    cmd = [
        "xcrun", "simctl", "launch", "--terminate-running-process", udid, IOS_BUNDLE_ID,
        IOS_DEV_LOGIN_EMAIL_ARG, state["email"],
        IOS_DEV_LOGIN_PASSWORD_ARG, state["password"],
    ]
    result = _run_tool(cmd, timeout=60)
    if result is None or result.returncode != 0:
        detail = (result.stderr.strip() if result else "") or "could not run simctl"
        log(f"WARNING: could not launch {IOS_BUNDLE_ID} on the simulator ({detail})")
        return False
    show_simulator(udid)
    log(f"launched {IOS_BUNDLE_ID} on the simulator (signs in as {state['email']} "
        "if signed out)")
    return True


def run_xcode_install(
    state: dict, state_dir: Path, url: str, save, *, reset_keychain: bool, udid: str | None
) -> bool:
    """Build the debug app and (re)install it on simulator ``udid``.

    Launching is left to the caller (launch_ios_app): ``up`` installs before
    the server listens, and a launch then would try to sign in to nothing.

    Warn-only at every step, exactly like run_gradle_install: a missing Xcode or
    simulator must never take the stack down. CODE_SIGNING_ALLOWED=NO is
    deliberately NOT passed -- an unsigned app cannot reach the Keychain, so the
    login token would never persist and the app would look signed out on every
    launch (it stays fine for `xcodebuild test`).

    The stale-install check reads ``installed_url``, which is written only after
    an install succeeds -- ``baked_url`` moves at sync time, so a sync-now /
    install-later run (the flow the READY banner prints) would otherwise think
    the simulator already carried the new URL.
    """
    if sys.platform != "darwin":
        log("WARNING: the iOS app can only be built on macOS; skipping app install")
        return False
    if not IOS_XCODEPROJ_PATH.exists():
        log(f"WARNING: {IOS_XCODEPROJ_PATH} not found; skipping iOS app install")
        return False
    if udid is None:
        log("WARNING: no iOS simulator available; skipping iOS app install")
        return False

    derived = state_dir / "ios-build"
    log(f"building + installing the debug app (xcodebuild -scheme {IOS_SCHEME}) ...")
    try:
        result = subprocess.run(
            [
                "xcodebuild",
                "-project", str(IOS_XCODEPROJ_PATH),
                "-scheme", IOS_SCHEME,
                "-configuration", "Debug",
                "-destination", f"platform=iOS Simulator,id={udid}",
                "-derivedDataPath", str(derived),
                "build",
            ],
            cwd=str(REPO_ROOT),
        )
    except OSError as exc:
        log(f"WARNING: could not run xcodebuild ({exc}); install the app manually")
        return False
    if result.returncode != 0:
        log(
            "WARNING: xcodebuild failed (needs Xcode and an iOS simulator "
            "runtime); the stack itself is unaffected"
        )
        return False

    app = derived / "Build" / "Products" / "Debug-iphonesimulator" / f"{IOS_SCHEME}.app"
    if not app.exists():
        log(f"WARNING: built app not found at {app}; skipping install")
        return False

    # Keyed by UDID: every simulator carries its own container AND its own
    # keychain, so an install on one says nothing about the state of another.
    installed = IOS_URL_FILE.own_state(state).setdefault("installed_urls", {})
    cleaned = True
    if installed.get(udid) != url:
        # TokenStore and ConnectionStore both persist a relay base URL in the
        # keychain, and an upgrade install would keep opening agent sockets
        # against the old stack while REST already followed the new baked URL.
        # Measured on the simulator: `simctl uninstall` wipes the container but
        # leaves those items intact, so only a keychain reset actually clears
        # them -- and simctl scopes reset per device, never per app.
        log("installed URL differs on this simulator: uninstalling the previous build")
        subprocess.run(["xcrun", "simctl", "uninstall", udid, IOS_BUNDLE_ID])
        installed.pop(udid, None)
        save()
        if reset_keychain:
            log(f"resetting the {udid[:8]}... simulator keychain (uninstall does "
                "not clear the stored relay URL; this drops every keychain item "
                "on that device, including `simctl keychain add-root-cert` "
                "anchors -- skip it with --ios-keep-keychain)")
            try:
                cleaned = subprocess.run(
                    ["xcrun", "simctl", "keychain", udid, "reset"]
                ).returncode == 0
            except OSError as exc:
                log(f"WARNING: could not run `simctl keychain reset` ({exc})")
                cleaned = False
            if not cleaned:
                log("WARNING: the keychain reset failed, so the previous stack's "
                    "relay URL may still be there; leaving this simulator marked "
                    "stale so the next --install-app retries the cleanup")
        else:
            log("WARNING: --ios-keep-keychain: the previous stack's relay URL "
                "survives in the keychain. If the app still talks to the old "
                "server, sign out in-app or reset the keychain by hand")
    cmd = ["xcrun", "simctl", "install", udid, str(app)]
    try:
        result = subprocess.run(cmd)
    except OSError as exc:
        log(f"WARNING: `{' '.join(cmd)}` could not run ({exc})")
        return False
    if result.returncode != 0:
        log(f"WARNING: `{' '.join(cmd)}` failed")
        return False
    if cleaned and installed.get(udid) != url:
        installed[udid] = url
        save()
    log("debug app installed on the simulator")
    return True


