def cmd_up(args: argparse.Namespace) -> int:
    if args.fresh and args.state_dir.exists():
        log(f"--fresh: wiping state dir {args.state_dir}")
        shutil.rmtree(args.state_dir, ignore_errors=True)

    deps = load_deps(auto_install=True, reinstall=args.reinstall)

    state_dir = args.state_dir
    server_dir = state_dir / "server"
    agent_dir = state_dir / "agent"
    logs_dir = state_dir / "logs"
    for d in (server_dir, agent_dir, logs_dir):
        d.mkdir(parents=True, exist_ok=True)

    state = load_or_create_state(state_dir, args)
    save = lambda: save_state(state_dir, state)  # noqa: E731
    save()

    kill_stale_processes(state, deps.psutil)
    check_port_free(args.host, args.port)

    lan_ip, all_ips = detect_lan_ips(deps.psutil)
    if args.advertise_ip:
        lan_ip = args.advertise_ip

    android_synced = False
    android_url = None
    rebuild_needed = False
    if not args.no_android:
        android_url = resolve_android_url(args, lan_ip)
        rebuild_needed = sync_android_files(state, android_url, save)
        android_synced = True
        if args.install_app:
            run_gradle_install()

    if os.name == "nt" and args.host not in ("127.0.0.1", "localhost"):
        log(
            "binding 0.0.0.0: watch for the Windows Defender Firewall prompt on "
            "first run and ALLOW Python on Private networks, or the phone cannot connect"
        )

    server = None
    agent = None
    client = None
    exit_code = 0
    try:
        log(f"starting central_server on {args.host}:{args.port} (MOBAIDE_ENV=test)")
        server = ChildProcess(
            "server",
            [sys.executable, "-u", "-m", "central_server"],
            build_server_env(state, args, server_dir),
            server_dir,
            logs_dir / "server.log",
        )
        state["runtime"] = {"server_pid": server.proc.pid, "started_at": _utc_now()}
        save()
        wait_for_http_ok(
            deps,
            f"http://127.0.0.1:{args.port}/api/health",
            timeout=90,
            child=server,
        )

        client = deps.mmc.MockMobileClient(f"http://127.0.0.1:{args.port}")
        provision(deps, client, state, save)

        agent_port = free_loopback_port()
        mode = "fake echo PTY (test mode)" if args.fake_pty else "real PTY (production mode)"
        log(f"starting mobaide agent with {mode}")
        agent = ChildProcess(
            "agent",
            [sys.executable, "-u", "-m", "mobaide"],
            build_agent_env(state, args, agent_dir, agent_port),
            agent_dir,
            logs_dir / "agent.log",
        )
        state["runtime"]["agent_pid"] = agent.proc.pid
        save()
        wait_for_http_ok(
            deps,
            f"http://127.0.0.1:{agent_port}/api/health",
            timeout=60,
            child=agent,
            expect_status_ok=True,
        )
        # The 4012-safe gate: agent's relay tunnel is up, not just its HTTP port.
        client.wait_agents_online(1, timeout=45)
        log("agent tunnel is online (agents_online >= 1)")

        if args.smoke:
            if args.fake_pty:
                run_smoke(deps, client, state)
            else:
                log("--smoke needs --fake-pty (deterministic echo backend); skipping")

        print_ready_banner(
            args, state, lan_ip, all_ips, android_synced, android_url, rebuild_needed
        )

        while True:
            time.sleep(1)
            for child in (server, agent):
                if not child.alive():
                    child.dump_tail()
                    log(f"{child.name} exited unexpectedly "
                        f"(code {child.proc.returncode}); shutting down")
                    exit_code = 1
                    return exit_code
    except KeyboardInterrupt:
        log("Ctrl+C: shutting down")
        return exit_code
    finally:
        for child in (agent, server):  # reverse boot order
            if child is not None:
                child.stop(deps.psutil)
        if client is not None:
            client.close()
        state["runtime"] = {}
        if (state_dir / "state.json").exists():
            # Skip the save when `clean` removed the state dir mid-run --
            # rewriting it here would resurrect a directory the user deleted.
            save()
        log(f"stack stopped; state kept in {state_dir} (next `up` reuses it)")


def cmd_android(args: argparse.Namespace) -> int:
    state_dir = args.state_dir
    state = load_or_create_state(state_dir, args)
    save = lambda: save_state(state_dir, state)  # noqa: E731

    if args.revert:
        revert_android_files(state, save)
        return 0

    psutil_mod = None
    try:
        import psutil as psutil_mod  # type: ignore[no-redef]
    except ImportError:
        pass  # candidates list degrades gracefully; primary detection is stdlib
    lan_ip, _ = detect_lan_ips(psutil_mod)
    if args.advertise_ip:
        lan_ip = args.advertise_ip
    url = resolve_android_url(args, lan_ip)
    changed = sync_android_files(state, url, save)
    if changed:
        log("URL changed: rebuild + reinstall the debug app so it bakes the new value")
    if args.install_app:
        run_gradle_install()
    return 0


def cmd_status(args: argparse.Namespace) -> int:
    state_path = args.state_dir / "state.json"
    state = None
    if state_path.exists():
        try:
            state = json.loads(state_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            pass
    port = args.port or (state or {}).get("server_port") or DEFAULT_PORT

    if state:
        log(f"state dir: {args.state_dir}")
        log(f"account:   {state.get('email')}")
        log(f"agent:     {state.get('agent_name')} ({(state.get('agent_id') or '-')[:8]}...)")
        android = state.get("android") or {}
        if android.get("managed_url"):
            log(f"android:   CENTRAL_SERVER_URL={android['managed_url']}")
    else:
        log(f"no state at {state_path} (stack never ran with this --state-dir)")

    deps = load_deps(auto_install=False)
    try:
        resp = deps.httpx.get(f"http://127.0.0.1:{port}/api/health", timeout=3)
        health = resp.json()
        log(
            f"server:    UP on port {port} -- status={health.get('status')} "
            f"agents_online={health.get('agents_online')} "
            f"agents_registered={health.get('agents_registered')}"
        )
        return 0
    except Exception as exc:  # noqa: BLE001
        log(f"server:    DOWN on port {port} ({type(exc).__name__})")
        return 1


def cmd_clean(args: argparse.Namespace) -> int:
    state_dir = args.state_dir
    state_path = state_dir / "state.json"
    state = None
    if state_path.exists():
        try:
            state = json.loads(state_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            state = None

    if state:
        try:
            import psutil as psutil_mod

            kill_stale_processes(state, psutil_mod)
        except ImportError:
            log("psutil not installed; skipping stale-process reaping")
        revert_android_files(state, lambda: None)

    if state_dir.exists():
        if state_path.exists() or not any(state_dir.iterdir()):
            shutil.rmtree(state_dir, ignore_errors=True)
            log(f"removed state dir {state_dir}")
        else:
            die(
                f"{state_dir} does not look like a manual-stack state dir "
                "(no state.json); refusing to delete it"
            )
    else:
        log(f"state dir {state_dir} already absent")
    return 0


