def resolve_android_url(args: argparse.Namespace, lan_ip: str) -> str:
    mode = args.android_url
    if mode == "auto":
        if getattr(args, "all", False) and args.host in ("0.0.0.0", "::", "", None):
            # --all always boots the emulator, and on a wildcard bind its
            # host alias stays valid when the Wi-Fi (and so the LAN IP) changes.
            return f"http://10.0.2.2:{args.port}"
        if args.host in ("127.0.0.1", "localhost"):
            # Loopback bind: the LAN IP is unreachable; 10.0.2.2 maps to the
            # host's loopback from an emulator, which is the usual reason to
            # bind loopback in the first place.
            return f"http://10.0.2.2:{args.port}"
        if args.host not in ("0.0.0.0", "::", "", None):
            # Bound to one specific interface: that address is the only
            # reachable one, regardless of which NIC auto-detection favors.
            return f"http://{args.host}:{args.port}"
        return f"http://{lan_ip}:{args.port}"
    if mode == "emulator":
        return f"http://10.0.2.2:{args.port}"
    if mode == "reverse":
        return f"http://127.0.0.1:{args.port}"
    if mode.startswith(("http://", "https://")):
        return mode
    die(f"--android-url must be auto|emulator|reverse or an explicit http(s) URL, got: {mode}")


def resolve_ios_url(args: argparse.Namespace, lan_ip: str) -> str:
    """URL for the iOS build. Unlike Android, ``auto`` prefers loopback.

    The simulator shares the Mac's network stack, and loopback is the only
    cleartext host iOS permits out of the box: the app's Info.plist carries no
    NSAppTransportSecurity exception, so http:// to a LAN address fails every
    URLSession REST call with -1022 while ws:// keeps working (Network.framework
    is not policed by ATS) -- a half-broken state worth steering away from.
    """
    mode = args.ios_url
    if mode == "auto":
        if args.host in ("0.0.0.0", "::", "", None, "127.0.0.1", "localhost"):
            return f"http://127.0.0.1:{args.port}"
        # Bound to one specific interface: loopback would miss the listener.
        return f"http://{args.host}:{args.port}"
    if mode == "simulator":
        return f"http://127.0.0.1:{args.port}"
    if mode == "lan":
        return f"http://{lan_ip}:{args.port}"
    if mode.startswith(("http://", "https://")):
        return mode
    die(f"--ios-url must be auto|simulator|lan or an explicit http(s) URL, got: {mode}")


def warn_if_ats_blocked(url: str) -> None:
    if not url.startswith("http://") or _is_loopback_url(url):
        return
    log(
        "WARNING: iOS App Transport Security blocks cleartext http:// to "
        f"{_url_host(url)}. Sign-in and every other REST call will fail with "
        "-1022 while terminals still connect (WebSockets bypass ATS), unless "
        "you add an NSAppTransportSecurity exception to "
        "ios/Mobaide/Support/Info.plist by hand. Use the simulator over "
        "loopback (--ios-url simulator) to avoid this entirely."
    )


def sync_android_files(state: dict, url: str, save) -> bool:
    """Write both gitignored Android artifacts; returns True when the app must
    be rebuilt + reinstalled because the URL baked into the last build changed.
    """
    release_other_checkout(state, "android", revert_android_files, save)
    rebuild_needed = ANDROID_URL_FILE.sync(state, url)

    nsc_rel = DEBUG_NSC_PATH.relative_to(REPO_ROOT).as_posix()
    existing_nsc = (
        DEBUG_NSC_PATH.read_text(encoding="utf-8") if DEBUG_NSC_PATH.exists() else None
    )
    if existing_nsc == DEBUG_NSC_CONTENT:
        log(f"{nsc_rel}: unchanged")
    elif existing_nsc is not None and NSC_MARKER not in existing_nsc:
        # Same ownership rule as revert: never clobber a hand-authored file.
        log(
            f"WARNING: {nsc_rel} exists but was not generated by this script; "
            "leaving it as is (make sure it permits cleartext to your stack, "
            "or delete it and re-run to let the script manage it)"
        )
    else:
        DEBUG_NSC_PATH.parent.mkdir(parents=True, exist_ok=True)
        DEBUG_NSC_PATH.write_text(DEBUG_NSC_CONTENT, encoding="utf-8", newline="\n")
        log(f"{nsc_rel}: written (debug builds only)")

    save()
    return rebuild_needed


def revert_android_files(state: dict, save) -> None:
    with checkout_paths(_client_checkout(state, "android")) as present:
        if present:
            _revert_android_files(state)
        else:
            log(f"android: checkout {_client_checkout(state, 'android')} is gone; "
                "nothing to revert")
            ANDROID_URL_FILE.forget_ownership(state)
    save()


def _revert_android_files(state: dict) -> None:
    ANDROID_URL_FILE.revert(state)

    if DEBUG_NSC_PATH.exists():
        content = DEBUG_NSC_PATH.read_text(encoding="utf-8")
        if NSC_MARKER in content:
            DEBUG_NSC_PATH.unlink()
            log(f"{DEBUG_NSC_PATH.relative_to(REPO_ROOT).as_posix()}: removed")
            # Prune the (empty) generated dirs: xml/ -> res/ -> debug/
            for directory in (
                DEBUG_NSC_PATH.parent,
                DEBUG_NSC_PATH.parent.parent,
                DEBUG_NSC_PATH.parent.parent.parent,
            ):
                try:
                    directory.rmdir()
                except OSError:
                    break
        else:
            log(
                f"{DEBUG_NSC_PATH.relative_to(REPO_ROOT).as_posix()}: not generated by this "
                "script (marker missing); leaving it alone"
            )
    else:
        log(f"{DEBUG_NSC_PATH.relative_to(REPO_ROOT).as_posix()}: absent; nothing to revert")


